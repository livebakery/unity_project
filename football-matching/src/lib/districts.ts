const DISTRICT_TO_ZONE: Record<string, string> = Object.entries(ZONES).reduce(
  (acc, [zone, districts]) => {
    for (const d of districts) acc[d] = zone;
    return acc;
  },
  {} as Record<string, string>,
);

export function zoneOf(district: string | null | undefined): string | null {
  if (!district) return null;
  return DISTRICT_TO_ZONE[district] ?? null;
}
